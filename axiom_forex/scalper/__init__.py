"""AX-SCALPER: an event-driven scalping desk, paper only.

The package is deliberately layered so that each layer can be read, tested and
blamed on its own:

``config``      declared terms, declared costs, declared limits — and the paper-only refusal
``ticks``       AX-TICK CORE: identity, ordering, freshness, gaps, latency, replay
``regime``      AX-REGIME: a label, an eligibility set, and a first-class NO TRADE
``signals``     five rule families with explicit, fingerprintable parameters
``bayes``       calibrated probabilities with uncertainty, and the broker-feed caveat
``ev``          expected net value = gross - spread - commission - slippage
``variance``    size from the stop, the equity and the permitted loss — never from a percentage
``guardian``    AX-GUARDIAN: the account-level authority both engines answer to
``execution``   a paper venue with rejects, partials and ambiguous outcomes; a trader that never guesses
``positions``   AX-POSITION MANAGER: break-even, trailing, time exits, protection verification
``scribe``      AX-SCRIBE: an append-only hash-chained ledger, losers included
``skeptic``     AX-SKEPTIC: walk-forward, PBO, deflated Sharpe, cost stress, and a refusal to approve
``desk``        the wiring: one tick in, at most one position out
``lab``         AX-LAB: replay, simulation, comparisons, degradation, reports

Nothing in this package can place a live order.  ``axiom_forex.brokers.mt5.orders``
is not imported anywhere here, and a test enforces that.
"""

