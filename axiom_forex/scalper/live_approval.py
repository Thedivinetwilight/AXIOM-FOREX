"""Signed approval of one exact AX-SCALPER LIVE plan.

This is a separate gate from evidence admission. It binds an independent
reviewer's signature to the exact typed intent, the exact armed plan identity,
the account/instrument/risk/config fingerprints, and the verified evidence
digest. It cannot create evidence, arm trading, connect a terminal, or submit an
order. A real deployment has no such approval by default; tests create ephemeral
keys and clearly synthetic documents.
"""
from __future__ import annotations

import base64
import hashlib
import json
from dataclasses import dataclass
from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path
from typing import Any, Mapping

from .admission import AdmissionPolicy, _canonical

APPROVAL_SCHEMA = "axiom-scalper-live-approval-v1"
APPROVAL_PHRASE = "APPROVE THIS EXACT LIVE PLAN"
CREDENTIAL_KEYS = frozenset({
    "password", "passwd", "pwd", "pass", "login", "account_login",
    "investor_password", "token", "access_token", "market_access_token",
    "api_key", "secret", "private_key",
})


class ApprovalError(ValueError):
    def __init__(self, reason: str, detail: str = ""):
        self.reason, self.detail = reason, detail
        super().__init__(reason if not detail else f"{reason}:{detail}")


def canonical_approval_payload(document: Mapping[str, Any]) -> bytes:
    """Bytes an independent reviewer signs; the signature itself is excluded."""
    return _canonical({key: value for key, value in document.items() if key != "signature"})


def _text(value: Any) -> str:
    if isinstance(value, Decimal):
        return str(value)
    return str(value if value is not None else "")


def plan_fingerprint(
    *,
    intent: Mapping[str, Any],
    plan: Mapping[str, Any],
    evidence_digest: str,
) -> str:
    """One stable content hash for the exact plan an operator may approve.

    Timestamps generated by the plan writer are intentionally excluded: they are
    bookkeeping, not trading semantics. Every value that changes what would be
    sent, where, under which identity, or under which risk ceiling is included.
    """
    keys = (
        "intent_id", "candidate_fingerprint", "evidence_fingerprint",
        "account_fingerprint", "instrument_fingerprint", "symbol",
        "broker_symbol", "timeframe", "side", "quantity", "quantity_unit",
        "stop_price", "target_price", "quote_bid", "quote_ask",
        "quote_timestamp", "quote_received_at", "quote_source",
        "expires_at", "risk_fingerprint", "config_fingerprint",
    )
    plan_keys = (
        "candidate_id", "pair", "broker_symbol", "timeframe", "quantity",
        "max_open_positions", "max_daily_loss_account",
        "protective_stop_pips", "account_currency", "evidence_state",
    )
    payload = {
        "schema": APPROVAL_SCHEMA,
        "evidence_digest": _text(evidence_digest),
        "intent": {key: _text(intent.get(key, "")) for key in keys},
        "plan": {key: _text(plan.get(key, "")) for key in plan_keys},
    }
    return hashlib.sha256(_canonical(payload)).hexdigest()


def approval_identity(intent: Mapping[str, Any], *, evidence_digest: str) -> dict[str, str]:
    """Exact fields a signed approval must repeat, with no inferred values."""
    keys = (
        "intent_id", "candidate_fingerprint", "evidence_fingerprint",
        "account_fingerprint", "instrument_fingerprint", "symbol",
        "broker_symbol", "timeframe", "side", "quantity", "quantity_unit",
        "stop_price", "target_price", "quote_bid", "quote_ask",
        "quote_timestamp", "quote_received_at", "quote_source", "expires_at",
        "risk_fingerprint", "config_fingerprint",
    )
    identity = {key: _text(intent.get(key, "")) for key in keys}
    # The approval has its own validity window; keep the intent's expiry under a
    # distinct name so neither timestamp can silently replace the other.
    identity["intent_expires_at"] = identity.pop("expires_at")
    identity["evidence_digest"] = _text(evidence_digest)
    identity["plan_phrase"] = APPROVAL_PHRASE
    return identity


@dataclass(frozen=True)
class ApprovalResult:
    valid: bool
    reason: str
    reviewer: str = ""
    reviewed_at: str = ""
    expires_at: str = ""
    fingerprint: str = ""

    def audit_view(self) -> dict[str, Any]:
        return {
            "valid": self.valid, "reason": self.reason, "reviewer": self.reviewer,
            "reviewed_at": self.reviewed_at, "expires_at": self.expires_at,
            "fingerprint": self.fingerprint,
        }


def _instant(value: Any, field: str) -> datetime:
    try:
        parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except (TypeError, ValueError):
        raise ApprovalError(f"approval_{field}_invalid") from None
    if parsed.tzinfo is None:
        raise ApprovalError(f"approval_{field}_timezone_missing")
    return parsed.astimezone(timezone.utc)


def _every_key(value: Any):
    if isinstance(value, Mapping):
        for key, child in value.items():
            yield str(key)
            yield from _every_key(child)
    elif isinstance(value, (list, tuple)):
        for child in value:
            yield from _every_key(child)


def verify_approval(
    path: str | Path,
    *,
    policy: AdmissionPolicy,
    expected_fingerprint: str,
    expected_identity: Mapping[str, Any],
    now: datetime | None = None,
) -> ApprovalResult:
    """Verify one signed exact-plan approval, or give a stable refusal reason."""
    target = Path(path)
    current = (now or datetime.now(timezone.utc)).astimezone(timezone.utc)

    def refuse(reason: str) -> ApprovalResult:
        return ApprovalResult(False, reason)

    try:
        document = json.loads(target.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return refuse("approval_missing")
    except (OSError, ValueError):
        return refuse("approval_unreadable")
    if not isinstance(document, dict):
        return refuse("approval_not_an_object")
    if any(str(key).strip().lower() in CREDENTIAL_KEYS for key in _every_key(document)):
        return refuse("approval_contains_credential_field")
    if document.get("schema") != APPROVAL_SCHEMA:
        return refuse("approval_schema_invalid")
    if str(document.get("plan_phrase") or "") != APPROVAL_PHRASE:
        return refuse("approval_phrase_mismatch")
    if str(document.get("plan_fingerprint") or "") != str(expected_fingerprint):
        return refuse("approval_plan_fingerprint_mismatch")
    for key, expected in expected_identity.items():
        if str(document.get(key, "") or "") != str(expected):
            return refuse(f"approval_{key}_mismatch")
    reviewer = str(document.get("reviewer_id") or "")
    encoded_key = policy.trusted_reviewers.get(reviewer)
    if not encoded_key:
        return refuse("approval_reviewer_untrusted")
    developers = document.get("strategy_developers")
    if not isinstance(developers, list) or reviewer.lower() in {str(x).lower() for x in developers}:
        return refuse("approval_reviewer_not_independent")
    try:
        reviewed_at = _instant(document.get("reviewed_at"), "reviewed_at")
        expires_at = _instant(document.get("expires_at"), "expires_at")
    except ApprovalError as exc:
        return refuse(exc.reason)
    if reviewed_at > current or expires_at <= current or expires_at <= reviewed_at:
        return refuse("approval_time_window_invalid")
    try:
        from cryptography.exceptions import InvalidSignature
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

        public = Ed25519PublicKey.from_public_bytes(
            base64.b64decode(str(encoded_key), validate=True)
        )
        public.verify(
            bytes.fromhex(str(document.get("signature") or "")),
            canonical_approval_payload(document),
        )
    except ImportError:
        return refuse("approval_signature_verifier_unavailable")
    except (ValueError, TypeError, InvalidSignature):
        return refuse("approval_signature_invalid")
    fingerprint = hashlib.sha256(canonical_approval_payload(document)).hexdigest()
    return ApprovalResult(
        True, "approval_valid", reviewer, reviewed_at.isoformat(),
        expires_at.isoformat(), fingerprint,
    )


